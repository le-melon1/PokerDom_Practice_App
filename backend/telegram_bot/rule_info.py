def get_rule_info(flag: str) -> RuleInfo | None:
    return RULE_INFO.get(flag)


def render_rule_info_text(flag: str) -> str:
    info = RULE_INFO.get(flag)
    if info is None:
        return f"Нет описания для {flag}."
    title = FLAG_LABEL_RU.get(flag, flag)
    return (
        f"<b>{title}</b>\n\n"
        f"<b>Что и когда:</b>\n{info.what}\n\n"
        f"<b>Почему это работает:</b>\n{info.why}\n\n"
        f"<b>Уверенность:</b> {info.confidence}\n"
        f"<i>{info.stats}</i>"
    )


# Representative position used for charting range flags that vary by
# position (open/call/steal/iso/limp-behind ranges are all a dict keyed by
# position, not one fixed set) -- BTN for the "widen this range" rules
# (widest, most illustrative), SB/BB for the two blind-specific rules that
# only ever apply at that exact seat.
_CHART_POSITION = {
    "STEAL_WIDER_VS_NIT": "BTN",
    "TIGHT_BIG_ISO_RAISE_LIMPERS": "BTN",
    "LIMP_BEHIND_OVER_LIMPERS": "BTN",
    "ALLOW_CALLING_RAISES": "BTN",
    "SB_THREEBET_OR_FOLD_VS_STEAL": "SB",
    "BB_DEFEND_VS_STEAL_MINRAISE": "BB",
    "BB_DEFEND_MDF_SCALED": "BB",
}


def chart_notations_for(flag: str) -> tuple[frozenset[str], str] | None:
    """Returns (hand set, chart subtitle) for this flag's actual range, read
    directly from abc_bot.py's own range caches/constants -- the real range
    the rule uses, not a proxy. None if this flag isn't range-based (most
    postflop rules aren't, they're about board texture/opponent
    reads/sizing, not hand selection)."""
    open_r, call_r, steal_r, tight_iso_r, _, _, limp_behind_r, bb_defend_r = abc_bot._ranges()

    if flag == "SET_MINE_IMPLIED_ODDS":
        return frozenset(abc_bot.SET_MINE_POCKET_PAIRS | abc_bot.SET_MINE_SUITED_CONNECTORS), "весь стол"
    if flag == "SIZE_UP_PREMIUM_OPENS":
        return frozenset(abc_bot.VALUE_3BET_TIGHT), "весь стол"
    if flag == "USE_WIDE_VALUE_3BET":
        return frozenset(abc_bot.VALUE_3BET_WIDE), "весь стол"
    if flag == "SHOVE_AA_KK_VS_3BET_PLUS":
        return frozenset(abc_bot.SHOVE_VS_3BET_PLUS_RANGE), "весь стол"
    if flag == "WIDER_3BET_VS_LOOSE":
        return frozenset(abc_bot.VALUE_3BET_VS_LOOSE), "весь стол"
    if flag in ("BLUFF_3BET_VS_TIGHT", "THREEBET_BLUFF_FROM_LATE_POSITION_ANY_OPPONENT"):
        return frozenset(abc_bot.BLUFF_3BET_RANGE), "весь стол"

    position = _CHART_POSITION.get(flag)
    if position is None:
        return None
    if flag == "STEAL_WIDER_VS_NIT":
        return frozenset(steal_r.get(position, set())), position
    if flag == "TIGHT_BIG_ISO_RAISE_LIMPERS":
        return frozenset(tight_iso_r.get(position, set())), position
    if flag == "LIMP_BEHIND_OVER_LIMPERS":
        return frozenset(limp_behind_r.get(position, set())), position
    if flag == "ALLOW_CALLING_RAISES":
        return frozenset(call_r.get(position, set())), position
    if flag == "SB_THREEBET_OR_FOLD_VS_STEAL":
        return frozenset((call_r.get("SB") or set()) | abc_bot.VALUE_3BET), position
    if flag in ("BB_DEFEND_VS_STEAL_MINRAISE", "BB_DEFEND_MDF_SCALED"):
        return frozenset(bb_defend_r.get("BB", set())), position
    return None
